"""Generate src/data/pokemon_trader_rarity.h: for each species, the catch rate
of its first evolution stage. The trader uses it as a rarity factor, so a
Gyarados is priced like a Magikarp line (common) and a Vaporeon like an Eevee
line (rare). Baby Pokémon (Pichu etc.) are ignored as pre-evolutions."""
import re, os
R = os.path.join(os.path.dirname(__file__), '..', '..')
evo = open(os.path.join(R, 'src/data/pokemon/evolution.h')).read()
info = open(os.path.join(R, 'src/data/pokemon/species_info.h')).read()
BABIES = {'PICHU', 'CLEFFA', 'IGGLYBUFF', 'TOGEPI', 'TYROGUE', 'SMOOCHUM', 'ELEKID', 'MAGBY', 'AZURILL', 'WYNAUT'}
pre = {}
for m in re.finditer(r'\[SPECIES_(\w+)\]\s*=\s*\{(.*?)\},?\n', evo):
    src = m.group(1)
    if src in BABIES:
        continue
    for dst in re.findall(r'SPECIES_(\w+)\}', m.group(2)):
        pre.setdefault(dst, src)
rate = {m.group(1): int(m.group(2)) for m in re.finditer(
    r'\[SPECIES_(\w+)\]\s*=\s*\{.*?\.catchRate = (\d+)', info, re.S)}
lines = []
for sp, r in rate.items():
    root = sp
    while root in pre:
        root = pre[root]
    lines.append(f'    [SPECIES_{sp}] = {rate.get(root, r)},')
out = ('// Generated by tools/pokemon_inc/gen_rarity.py. Do not edit.\n'
       '// Catch rate of each species\' first evolution stage (rarity factor).\n'
       'static const u8 sBaseFormCatchRate[NUM_SPECIES] = {\n' + '\n'.join(lines) + '\n};\n')
open(os.path.join(R, 'src/data/pokemon_trader_rarity.h'), 'w').write(out)
print(len(lines), 'species')
